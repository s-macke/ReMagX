import { test, expect } from './fixtures'

test('Materials preserves read-only fields, discards Cancel/Escape and applies edits and fit flags as one undo step', async ({ page }) => {
  await page.goto('/')
  const cell = page.getByRole('textbox', { name: 'thickness of layer 1', exact: true })
  const open = async () => {
    await cell.click({ button: 'right' })
    await page.getByRole('menuitem', { name: 'Properties', exact: true }).click()
  }
  await open()
  const dialog = page.getByRole('dialog', { name: 'Material Settings', exact: true })
  for (const name of ['Name', 'Thickness', 'Roughness', 'δ', 'β', 'δm', 'βm']) await expect(dialog.getByRole('textbox', { name, exact: true })).toHaveAttribute('readonly', '')
  expect(await dialog.locator('input').evaluateAll(inputs => inputs.every(input => {
    const bounds = input.getBoundingClientRect()
    const group = input.closest('fieldset')!.getBoundingClientRect()
    return bounds.left >= group.left && bounds.right <= group.right
  }))).toBe(true)
  await expect(dialog).toContainText('Tensor values are not available from the mock engine')
  await dialog.getByRole('textbox', { name: 'Chemical Formula', exact: true }).fill('cancelled')
  await dialog.getByRole('checkbox', { name: 'Fit Gamma', exact: true }).check()
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Undo (Ctrl+Z)', exact: true })).toBeDisabled()
  await open()
  await expect(dialog.getByRole('textbox', { name: 'Chemical Formula', exact: true })).not.toHaveValue('cancelled')
  await expect(dialog.getByRole('checkbox', { name: 'Fit Gamma', exact: true })).not.toBeChecked()
  await dialog.getByRole('spinbutton', { name: 'Density', exact: true }).fill('-1')
  await dialog.getByRole('button', { name: 'OK', exact: true }).click()
  await expect(dialog).toBeVisible()
  await dialog.getByRole('spinbutton', { name: 'Density', exact: true }).fill('6.5')
  await dialog.getByRole('textbox', { name: 'Chemical Formula', exact: true }).fill('CoO')
  await dialog.getByRole('spinbutton', { name: 'Gamma', exact: true }).fill('37')
  await dialog.getByRole('spinbutton', { name: 'Phi', exact: true }).fill('42')
  await dialog.getByRole('checkbox', { name: 'Fit Gamma', exact: true }).check()
  await dialog.getByRole('checkbox', { name: 'Fit Phi', exact: true }).check()
  await dialog.getByRole('button', { name: 'OK', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('textbox', { name: 'material of layer 1', exact: true })).toHaveValue('CoO')
  await expect(page.getByRole('textbox', { name: 'density of layer 1', exact: true })).toHaveValue('6.5')
  await expect(cell).toHaveValue('10')
  await page.getByRole('tab', { name: 'Fit', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Parameters (2)', exact: true })).toBeVisible()
  await page.getByRole('textbox', { name: 'optical table of layer 1', exact: true }).focus()
  await page.keyboard.press('Shift+F10')
  await page.getByRole('menuitem', { name: 'Properties', exact: true }).click()
  await expect(dialog.getByRole('spinbutton', { name: 'Gamma', exact: true })).toHaveValue('37')
  await expect(dialog.getByRole('checkbox', { name: 'Fit Phi', exact: true })).toBeChecked()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await page.getByRole('button', { name: 'Undo (Ctrl+Z)', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Parameters (0)', exact: true })).toBeVisible()
  await expect(page.getByRole('textbox', { name: 'material of layer 1', exact: true })).not.toHaveValue('CoO')
  await expect(page.getByRole('button', { name: 'Undo (Ctrl+Z)', exact: true })).toBeDisabled()
})

test('undo while a material draft is open discards the stale dialog even without an active fit', async ({ page }) => {
  await page.goto('/')
  const cell = page.getByRole('textbox', { name: 'thickness of layer 1', exact: true })
  await cell.fill('11')
  await cell.press('Enter')
  await cell.click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Properties', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Material Settings', exact: true })
  await dialog.getByRole('textbox', { name: 'Chemical Formula', exact: true }).fill('stale draft')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).focus()
  await page.keyboard.press('Control+z')
  await expect(dialog).toHaveCount(0)
  await expect(cell).toHaveValue('10')
  await expect(page.getByRole('textbox', { name: 'material of layer 1', exact: true })).not.toHaveValue('stale draft')
})
