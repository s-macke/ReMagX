import { test, expect } from './fixtures'

test('segmentation illustration toggles both profile plots and exports without editing the project', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/')
  await page.getByRole('tab', { name: 'Sample', exact: true }).click()
  const section = page.getByRole('button', { name: 'Adaptive Layer Segmentation', exact: true })
  if (await section.getAttribute('aria-expanded') !== 'true') await section.click()
  const illustrate = page.getByRole('checkbox', { name: 'Illustrate Segmentation', exact: true })
  await expect(illustrate).toBeChecked()
  await page.getByRole('button', { name: 'Show Optical Profile', exact: true }).click()
  await expect(page.getByLabel('Plot axis: z', { exact: true })).toBeVisible()
  const rows = async () => {
    const menu = page.locator('.plot-panel__export')
    if (await menu.getAttribute('open') === null) await menu.locator('summary').click()
    await page.getByRole('button', { name: 'Copy data to clipboard', exact: true }).click()
    await expect(page.locator('.plot-panel__export-message')).toHaveText('Diagram data copied.')
    return (await page.evaluate(() => navigator.clipboard.readText())).trim().split('\n').filter(line => !line.startsWith('#')).map(line => line.split('\t').map(Number))
  }
  const steps = await rows()
  expect(steps[0][0]).toBe(steps[1][0])
  expect(steps[1][1]).toBe(0)
  await illustrate.uncheck()
  await expect.poll(async () => (await rows()).length).toBeLessThan(steps.length)
  const smooth = await rows()
  expect(smooth[1][0]).toBeGreaterThan(smooth[0][0])
  await page.getByRole('button', { name: 'Show Magneto-optical Profile', exact: true }).click()
  await expect(page.locator('.plot-panel__legend')).toContainText('δm')
  await illustrate.check()
  await expect.poll(async () => (await rows()).length).toBe(steps.length)
  expect((await rows())[1][1]).toBe(0)
  await expect(page.getByRole('button', { name: 'Undo (Ctrl+Z)', exact: true })).toBeDisabled()
  await section.click()
  await section.click()
  await expect(illustrate).toBeChecked()
})

test('To layer list previews, cancels, applies atomically and restores the stack with undo', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('tab', { name: 'Sample', exact: true }).click()
  const section = page.getByRole('button', { name: 'Adaptive Layer Segmentation', exact: true })
  if (await section.getAttribute('aria-expanded') !== 'true') await section.click()
  const count = await page.locator('.layer-table tbody tr').count()
  const open = page.getByRole('button', { name: 'To layer list', exact: true })
  await open.click()
  const dialog = page.getByRole('dialog', { name: 'To layer list', exact: true })
  await expect(dialog).toContainText('Mock conversion')
  const apply = dialog.getByRole('button', { name: 'Apply mock layers', exact: true })
  await expect(apply).toBeEnabled()
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.locator('.layer-table tbody tr')).toHaveCount(count)
  await expect(page.getByRole('button', { name: 'Undo (Ctrl+Z)', exact: true })).toBeDisabled()
  await open.click()
  await expect(apply).toBeEnabled()
  await apply.click()
  await expect.poll(() => page.locator('.layer-table tbody tr').count()).toBeGreaterThan(count)
  await page.getByRole('button', { name: 'Undo (Ctrl+Z)', exact: true }).click()
  await expect(page.locator('.layer-table tbody tr')).toHaveCount(count)
  await expect(page.getByRole('textbox', { name: 'thickness of layer 1', exact: true })).toHaveValue('10')
})
