import { test, expect } from './fixtures'

test('magnetization fit parameters select a layer and transfer values only to that layer', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('tab', { name: 'Sample', exact: true }).click()
  await page.getByRole('button', { name: 'Magneto-Optics', exact: true }).click()
  await page.getByRole('radio', { name: 'add magnetization', exact: true }).check()
  const gamma = page.getByRole('textbox', { name: 'magnetization gamma of layer 2', exact: true })
  await gamma.fill('31')
  await gamma.press('Enter')
  await page.getByRole('tab', { name: 'Fit', exact: true }).click()
  const header = page.getByRole('button', { name: 'Parameters (0)', exact: true })
  if (await header.getAttribute('aria-expanded') !== 'true') await header.click()
  const add = page.getByRole('group', { name: 'Add parameter', exact: true })
  await add.getByRole('combobox', { name: 'quantity', exact: true }).selectOption('magnetizationGamma')
  await add.getByRole('combobox', { name: 'of', exact: true }).selectOption('2')
  await add.getByRole('button', { name: 'Add', exact: true }).click()
  const row = page.getByRole('row').filter({ has: page.getByRole('rowheader', { name: 'magnetization γ (layer 2)', exact: true }) })
  await expect(row.getByRole('textbox', { name: 'start value', exact: true })).toHaveValue('31')
  await row.getByRole('textbox', { name: 'start value', exact: true }).fill('24')
  await row.getByRole('textbox', { name: 'start value', exact: true }).press('Enter')
  await page.getByRole('button', { name: 'Values → table', exact: true }).click()
  await expect(gamma).toHaveValue('24')
  await expect(page.getByRole('textbox', { name: 'magnetization gamma of layer 1', exact: true })).toHaveValue('90')
  await page.getByRole('button', { name: 'Undo (Ctrl+Z)', exact: true }).click()
  await expect(gamma).toHaveValue('31')
  await page.getByRole('tab', { name: 'Sample', exact: true }).click()
  await expect(page.getByRole('group', { name: 'Magnetization direction', exact: true }).getByRole('textbox', { name: 'gamma', exact: true })).toHaveValue('90')
})
