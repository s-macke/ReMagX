import { test, expect, loadEnergyTables } from './fixtures'

test('plot properties validate, apply and cancel ranges and appearance independently of other views', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'Properties', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Plot Properties', exact: true })
  await dialog.getByLabel('X min', { exact: true }).fill('0.2')
  await dialog.getByLabel('X max', { exact: true }).fill('0.1')
  await dialog.getByRole('button', { name: 'Apply', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('maximum')
  await dialog.getByLabel('X min', { exact: true }).fill('0.01')
  await dialog.getByLabel('X max', { exact: true }).fill('0.4')
  await dialog.getByLabel('X logscale', { exact: true }).check()
  await dialog.getByLabel('Y logscale', { exact: true }).uncheck()
  await dialog.getByLabel('Y min', { exact: true }).fill('0')
  await dialog.getByLabel('Y max', { exact: true }).fill('1')
  await dialog.getByLabel('X steps', { exact: true }).fill('4')
  await dialog.getByLabel('Border', { exact: true }).fill('#123456')
  await dialog.getByLabel('Background', { exact: true }).fill('#345678')
  await dialog.getByLabel('Pen color 1', { exact: true }).fill('#fedcba')
  await dialog.getByLabel('Font size', { exact: true }).fill('15')
  await dialog.getByLabel('Line width', { exact: true }).fill('3')
  await dialog.getByLabel('Show points', { exact: true }).check()
  await dialog.getByRole('button', { name: 'Apply', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect.poll(() => page.locator('.uplot canvas').evaluate((canvas: HTMLCanvasElement) => [...canvas.getContext('2d')!.getImageData(0, 0, 1, 1).data])).toEqual([18, 52, 86, 255])
  await expect(page.locator('.plot-panel__swatch').first()).toHaveCSS('background-color', 'rgb(254, 220, 186)')
  await page.getByRole('button', { name: 'Properties', exact: true }).click()
  await expect(dialog.getByLabel('X min', { exact: true })).toHaveValue('0.01')
  await expect(dialog.getByLabel('X max', { exact: true })).toHaveValue('0.4')
  await expect(dialog.getByLabel('X steps', { exact: true })).toHaveValue('4')
  await expect(dialog.getByLabel('Show points', { exact: true })).toBeChecked()
  await dialog.getByLabel('X max', { exact: true }).fill('0.2')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Properties', exact: true }).click()
  await expect(dialog.getByLabel('X max', { exact: true })).toHaveValue('0.4')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await loadEnergyTables(page)
  await page.getByRole('button', { name: 'Energy Scan', exact: true }).click()
  await expect(page.getByLabel('Plot axis: energy', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Properties', exact: true }).click()
  await expect(dialog.getByLabel('X logscale', { exact: true })).not.toBeChecked()
  expect(errors).toEqual([])
})
